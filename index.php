<script>

    // Mobile menu

    const menuButton =
        document.querySelector(".menu-btn");

    const navigation =
        document.querySelector(".navigation");


    if (menuButton) {

        menuButton.addEventListener(
            "click",
            function () {

                navigation.classList.toggle(
                    "active"
                );

            }
        );

    }



    // Add to cart

    const cartButtons =
        document.querySelectorAll(
            ".add-cart"
        );

    const cartCount =
        document.querySelector(
            ".cart-count"
        );


    let cartItems = 0;


    cartButtons.forEach(
        function (button) {

            button.addEventListener(
                "click",
                function () {

                    cartItems++;

                    cartCount.textContent =
                        cartItems;


                    button.textContent =
                        "Added ✓";


                    button.classList.add(
                        "added"
                    );


                    setTimeout(
                        function () {

                            button.textContent =
                                "Add to Cart";

                            button.classList.remove(
                                "added"
                            );

                        },
                        1500
                    );

                }
            );

        }
    );



    // Wishlist

    const wishlistButtons =
        document.querySelectorAll(
            ".wishlist"
        );


    wishlistButtons.forEach(
        function (button) {

            button.addEventListener(
                "click",
                function () {

                    if (
                        button.textContent
                            .trim() === "♡"
                    ) {

                        button.textContent =
                            "♥";

                    } else {

                        button.textContent =
                            "♡";

                    }

                }
            );

        }
    );



    // Newsletter

    const newsletter =
        document.querySelector(
            ".newsletter-form"
        );


    if (newsletter) {

        newsletter.addEventListener(
            "submit",
            function (event) {

                event.preventDefault();

                alert(
                    "Thank you for subscribing!"
                );

                newsletter.reset();

            }
        );

    }

</script>


